/**
 * Browser addon support.
 *
 * Camoufox loads **extracted** addon folders rather than `.xpi` archives, and the
 * engine reaches them through the config that `camoufox-js`'s `launchOptions()`
 * folds into `CAMOU_CONFIG_<n>` environment chunks. This module installs an
 * engine-side plugin that adds the configured addon folders to that config at the
 * `browser:launching` hook, and it is deliberately the only place that knows the
 * chunk-encoding detail.
 *
 * The engine loads plugins from `<repoPath>/plugins/<name>/index.js` and only
 * loads the directories named by `camofox.config.json`'s `plugins` key
 * (`camofox-browser/lib/plugins.js:147-212`). Neither path is configurable by an
 * outside caller — `server.js` calls `loadPlugins(app, pluginCtx)` without
 * overrides — so the integration owns writing into the engine checkout.
 *
 * @module dsh-camofox/addons
 */

import { existsSync, lstatSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

/** Engine plugin directory name this module owns. */
export const ENGINE_PLUGIN_NAME = 'dsh-addons'

/**
 * First line of the generated engine plugin.
 *
 * It identifies a file this module owns, so an operator's hand-edited copy is
 * left alone instead of being overwritten on every activation.
 */
const GENERATED_MARKER = '// Generated by dsh-camofox. Do not edit; it is rewritten on activation.'

export { GENERATED_MARKER }

/**
 * Chunk size `camoufox-js` uses when it splits the config across environment
 * variables: 2047 on Windows, 32767 elsewhere (`getEnvVars`, utils.js:34).
 *
 * @param {string} platform - Node platform identifier.
 * @returns {number} characters per environment chunk.
 */
export function configChunkSize(platform) {
  return platform === 'win32' ? 2047 : 32767
}

/**
 * Validate one addon folder the way `camoufox-js` will validate it.
 *
 * `confirmPaths` (`addons.js:14-24`) rejects a path that is missing, is not a
 * directory, or has no `manifest.json`. Checking here turns a browser launch
 * failure into a message naming the folder, because by launch time the engine
 * has already spent its readiness budget.
 *
 * The manifest version is read too. Firefox 152 has Manifest V2 disabled, so an
 * MV2 addon loads without any error and then never runs — the failure is
 * completely silent, which is worse than a refusal.
 *
 * @param {string} path - addon folder.
 * @returns {string|null} the problem, or null when the folder is usable.
 */
export function validateAddonFolder(path) {
  if (typeof path !== 'string' || path.trim() === '') {
    return 'addon path must be a non-empty string'
  }
  // `lstatSync`, not `existsSync`: camoufox-js checks
  // `!fs.lstatSync(path).isDirectory()` (addons.js:17), and lstat does not follow
  // a symlink, so a symlinked addon is REJECTED there. An `existsSync` check here
  // would pass a folder the engine then throws on, turning our validation into a
  // promise the launch cannot keep.
  let stats
  try {
    stats = lstatSync(path)
  } catch (error) {
    return `${path}: cannot be read (${error.message})`
  }
  if (!stats.isDirectory()) {
    return `${path}: is not a directory — Camoufox loads an EXTRACTED addon folder, not an .xpi archive`
  }
  let manifest
  try {
    manifest = JSON.parse(readFileSync(join(path, 'manifest.json'), 'utf-8'))
  } catch (error) {
    return `${path}: no readable manifest.json (${error.message})`
  }
  const version = manifest?.manifest_version
  if (version !== 3) {
    return `${path}: manifest_version is ${JSON.stringify(version ?? null)}, but this Firefox (152) has Manifest V2 disabled — an MV2 addon loads and never runs`
  }
  return null
}

/**
 * The engine-side plugin source.
 *
 * It is generated rather than shipped as a file so the addon paths are passed
 * through an environment variable: the engine copies a narrow variable set into
 * its own subprocess environment (`lib/config.js`), and an inline path list would
 * need that list duplicated in two places.
 *
 * @returns {string} the module source written to the engine checkout.
 */
function enginePluginSource() {
  return `${GENERATED_MARKER}
import fs from 'node:fs'

/**
 * Injects addon folders into the Camoufox launch config.
 *
 * camoufox-js consumes \`addons\` inside launchOptions() and encodes the resulting
 * config into CAMOU_CONFIG_<n> chunks on the resolved Playwright options, which
 * are emitted before \`browser:launching\` fires. Assigning \`options.addons\` at
 * this hook therefore has no effect; the config those chunks encode is the only
 * place an addon can still be added.
 *
 * @param {object} app - Express app.
 * @param {object} ctx - Shared plugin context.
 */
export function register(app, ctx) {
  const chunkSize = Number(process.env.CAMOFOX_DSH_CONFIG_CHUNK_SIZE) || (process.platform === 'win32' ? 2047 : 32767)
  const raw = process.env.CAMOFOX_DSH_ADDONS ?? ''
  const addons = raw.split('\\u0000').filter(Boolean)

  if (addons.length === 0) {
    ctx.log('info', 'dsh-addons: no addon folders configured')
  } else {
    ctx.log('info', 'dsh-addons: configured addon folders', { addons })
  }

  ctx.events.on('browser:launching', ({ options }) => {
    if (addons.length === 0) return

    const missing = addons.filter(p => !fs.existsSync(p))
    if (missing.length > 0) {
      ctx.log('warn', 'dsh-addons: addon folder is missing, skipping it', { missing })
    }
    const usable = addons.filter(p => fs.existsSync(p) && fs.existsSync(p + '/manifest.json'))
    if (usable.length === 0) return

    const env = options.env ?? (options.env = {})
    const chunkKeys = Object.keys(env).filter(k => /^CAMOU_CONFIG_\\d+$/.test(k)).sort()

    // camoufox-js splits ONE JSON string across chunks, so they concatenate.
    const raw_ = chunkKeys.map(k => env[k]).join('')
    let config = {}
    if (raw_) {
      try {
        config = JSON.parse(raw_)
      } catch (err) {
        ctx.log('error', 'dsh-addons: could not read the launch config', { error: err.message })
        return
      }
    }

    config.addons = [...new Set([...(config.addons ?? []), ...usable])]

    const str = JSON.stringify(config)
    for (const key of chunkKeys) delete env[key]
    let n = 0
    for (let i = 0; i < str.length; i += chunkSize) {
      n += 1
      env['CAMOU_CONFIG_' + n] = str.slice(i, i + chunkSize)
    }
    ctx.log('info', 'dsh-addons: injected addon folders', { addons: config.addons, chunks: n })
  })

  app.get('/dsh-addons/status', ctx.auth(), (req, res) => {
    res.json({
      addons,
      resolved: addons.map(p => ({
        path: p,
        exists: fs.existsSync(p),
        manifest: fs.existsSync(p + '/manifest.json'),
      })),
    })
  })
}
`
}

/**
 * Install the engine-side addon plugin into an engine checkout.
 *
 * The plugin directory and the `camofox.config.json` allowlist entry are written
 * together: without both, the engine silently skips the directory
 * (`lib/plugins.js:169-177`), which would look like the feature simply not
 * working. A checkout that already names the plugin is left alone so the
 * operator's own copy survives.
 *
 * @param {string} repoPath - engine checkout directory.
 * @param {string[]} addonPaths - absolute addon folder paths to load.
 * @param {string} platform - Node platform identifier, for chunk sizing.
 * @returns {{ installed: boolean, reason?: string, configPath: string, addons?: string[], rejected?: string[] }} the outcome.
 */
/**
 * Write one generated engine plugin into a checkout and allowlist it.
 *
 * The plugin directory and the `camofox.config.json` entry are written
 * together: without both, the engine silently skips the directory
 * (`lib/plugins.js:169-177`), which would look like the feature simply not
 * working.
 *
 * @param {string} repoPath - engine checkout directory.
 * @param {string} name - engine plugin directory name.
 * @param {() => string} generate - produces the module source.
 * @param {string} marker - first line identifying a file this module owns.
 * @returns {{ installed: boolean, reason?: string, configPath: string }} the outcome.
 */
export function writeEnginePlugin(repoPath, name, generate, marker) {
  let targetDir = repoPath
  const candidate = join(targetDir, 'node_modules', '@askjo', 'camofox-browser')
  if (existsSync(join(candidate, 'camofox.config.json'))) {
    targetDir = candidate
  }
  const configPath = join(targetDir, 'camofox.config.json')
  const pluginPath = join(targetDir, 'plugins', name, 'index.js')

  let config
  try {
    config = JSON.parse(readFileSync(configPath, 'utf-8'))
  } catch (error) {
    return { installed: false, reason: `cannot read ${configPath}: ${error.message}`, configPath }
  }

  // Preserve the allowlist-only-if-present behaviour: an absent `plugins` key
  // makes the engine load every directory, so adding one would narrow it.
  if (config.plugins && typeof config.plugins === 'object' && !Array.isArray(config.plugins)
    && !Object.prototype.hasOwnProperty.call(config.plugins, name)) {
    config.plugins[name] = { enabled: true }
    try {
      writeFileSync(configPath, `${JSON.stringify(config, null, 2)}\n`, 'utf-8')
    } catch (error) {
      return { installed: false, reason: `cannot update ${configPath}: ${error.message}`, configPath }
    }
  }

  // A hand-edited plugin file is the operator's own, and this module owns a
  // generated file with a known header. Anything else is left alone rather than
  // overwritten on every activation.
  let existing = null
  try {
    existing = readFileSync(pluginPath, 'utf-8')
  } catch {
    existing = null
  }
  const generated = generate()
  if (existing !== null && existing !== generated && !existing.startsWith(marker)) {
    return {
      installed: false,
      reason: `${pluginPath} exists and was not written by this plugin; move it aside to let the addon integration manage it`,
      configPath,
    }
  }

  try {
    mkdirSync(join(targetDir, 'plugins', name), { recursive: true })
    if (existing !== generated) writeFileSync(pluginPath, generated, 'utf-8')
  } catch (error) {
    return { installed: false, reason: `cannot write ${pluginPath}: ${error.message}`, configPath }
  }
  return { installed: true, configPath }
}

/**
 * Install the engine-side addon plugin into an engine checkout.
 *
 * @param {string} repoPath - engine checkout directory.
 * @param {string[]} addonPaths - absolute addon folder paths to load.
 * @param {string} platform - Node platform identifier, for chunk sizing.
 * @returns {{ installed: boolean, reason?: string, configPath: string, addons?: string[], rejected?: string[] }} the outcome.
 */
export function installAddonPlugin(repoPath, addonPaths, platform) {
  const configPath = join(repoPath, 'camofox.config.json')

  // Refuse a folder we can already prove is unusable, and say why. An addon that
  // loads and silently never runs is worse than one refused here.
  const rejected = []
  const usable = []
  for (const path of addonPaths) {
    const problem = validateAddonFolder(path)
    if (problem) rejected.push(problem)
    else usable.push(path)
  }

  // Nothing usable means nothing to install. Decided BEFORE any write so a
  // refused addon leaves the checkout exactly as it was, rather than installing
  // an engine plugin whose only configured folder is one we already know is dead.
  if (usable.length === 0 && rejected.length > 0) {
    return { installed: false, reason: rejected.join('; '), configPath, rejected }
  }

  const written = writeEnginePlugin(repoPath, ENGINE_PLUGIN_NAME, enginePluginSource, () => GENERATED_MARKER)
  if (!written.installed) return { ...written, rejected }

  // A folder that cannot possibly work is not a reason to deny the browser its
  // other addons, so the install proceeded above with whatever was usable and
  // names what it refused.
  return { installed: true, configPath: written.configPath, addons: usable, rejected, addonCount: usable.length, chunkSize: configChunkSize(platform) }
}
/**
 * Engine lifecycle and orphan process prevention.
 *
 * Ensures that when the parent DeepSeek Harness process terminates (gracefully,
 * unexpectedly, or abruptly via SIGKILL / crash), the engine and all its child
 * browser processes (Camoufox / Firefox / Playwright) terminate immediately.
 *
 * @module dsh-camofox/lifecycle-plugin
 */

/** Engine plugin directory name for lifecycle management. */
export const LIFECYCLE_PLUGIN_NAME = 'dsh-lifecycle'

/** First line identifying generated lifecycle plugin source. */
export const GENERATED_LIFECYCLE_MARKER = '// Generated by dsh-camofox. Do not edit; it is rewritten on activation.'

/**
 * Produce the source code for the engine-side lifecycle plugin.
 *
 * @returns {string} module source code.
 */
export function lifecyclePluginSource() {
  return `${GENERATED_LIFECYCLE_MARKER}
import fs from 'node:fs'

/**
 * Engine lifecycle plugin: monitors parent liveness and terminates all browser
 * processes when the parent DeepSeek Harness process terminates.
 *
 * @param {object} app - Express app.
 * @param {object} ctx - Shared plugin context.
 */
export function register(app, ctx) {
  const parentPid = Number(process.env.CAMOFOX_PARENT_PID)
  let exiting = false

  function killChildren() {
    const ownPid = process.pid
    try {
      if (process.platform === 'linux') {
        const entries = fs.readdirSync('/proc')
        for (let i = 0; i < entries.length; i++) {
          const entry = entries[i]
          if (entry.charCodeAt(0) < 48 || entry.charCodeAt(0) > 57) continue
          const p = Number(entry)
          if (!Number.isInteger(p) || p <= 0 || p === ownPid) continue
          try {
            const stat = fs.readFileSync('/proc/' + p + '/stat', 'utf8')
            const rP = stat.lastIndexOf(')')
            if (rP === -1) continue
            const parts = stat.slice(rP + 2).trimStart().split(' ')
            if (Number(parts[1]) === ownPid) {
              try { process.kill(p, 'SIGKILL') } catch {}
            }
          } catch {}
        }
      }
    } catch {}
  }

  function cleanupAndExit(reason) {
    if (exiting) return
    exiting = true
    try {
      if (ctx && typeof ctx.log === 'function') {
        ctx.log('info', 'dsh-lifecycle: shutting down engine (' + reason + ')')
      }
    } catch {}
    try {
      if (typeof ctx?.browser?.close === 'function') {
        ctx.browser.close().catch(() => {})
      }
    } catch {}
    killChildren()
    process.exit(0)
  }

  // 1. Listen for EOF on stdin (closed the instant parent process dies)
  if (process.stdin) {
    process.stdin.on('end', () => cleanupAndExit('parent stdin closed (EOF)'))
    process.stdin.on('close', () => cleanupAndExit('parent stdin closed'))
    try {
      process.stdin.resume()
    } catch {}
  }

  // 2. Poll parent liveness every 1000ms as a backstop
  if (Number.isInteger(parentPid) && parentPid > 0) {
    const timer = setInterval(() => {
      try {
        process.kill(parentPid, 0)
      } catch {
        cleanupAndExit('parent pid ' + parentPid + ' is no longer alive')
      }
    }, 1000)
    if (typeof timer.unref === 'function') timer.unref()
  }

  // 3. Clean up on signals
  process.on('SIGTERM', () => cleanupAndExit('SIGTERM'))
  process.on('SIGINT', () => cleanupAndExit('SIGINT'))
  process.on('SIGHUP', () => cleanupAndExit('SIGHUP'))
  process.on('exit', () => killChildren())

  // 4. Protect against page.setViewportSize hang in Camoufox (anti-fingerprint pinning)
  if (ctx && ctx.events) {
    ctx.events.on('tab:created', ({ page }) => {
      if (page && typeof page.setViewportSize === 'function') {
        const orig = page.setViewportSize.bind(page)
        page.setViewportSize = (size) => Promise.race([
          orig(size).catch(() => {}),
          new Promise((resolve) => setTimeout(resolve, 300)),
        ])
      }
    })
  }
}
`
}

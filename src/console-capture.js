/**
 * Browser console and network-error capture.
 *
 * Page-level failures are invisible from the outside: a JavaScript exception, a
 * failed API call and a rejected promise all leave the accessibility tree and
 * the extracted text looking perfectly healthy, so an agent reading a page has
 * no way to learn that the thing it is looking at never worked. This module
 * installs an engine-side plugin that attaches Playwright listeners to each tab
 * as it is created, and serves what they collected.
 *
 * The engine hands the live `page` object to `tab:created`
 * (`camofox-browser/server.js:3043`), so no engine change is needed. That event
 * also fires for popups (`server.js:1838`), which is what makes the capture
 * complete rather than only covering the first page.
 *
 * @module dsh-camofox/console-capture
 */

/** Engine plugin directory name this module owns. */
export const CONSOLE_PLUGIN_NAME = 'dsh-console'

/**
 * First line of the generated engine plugin, marking a file this module owns.
 */
export const GENERATED_CONSOLE_MARKER = '// Generated by dsh-camofox. Do not edit; it is rewritten on activation.'

/**
 * The engine-side plugin source.
 *
 * Four sources are captured, because they fail in four different ways and a
 * model needs all of them:
 *
 * - `console.error` / `console.warning` — the page's own complaints. `log` and
 *   `info` are deliberately NOT captured: a page that logs on every render
 *   would bury the two that matter.
 * - `pageerror` — an uncaught exception, which never reaches `console` at all.
 *   This is the one most often missed, and it is usually the actual cause.
 * - `requestfailed` — a request that never completed. A name that does not
 *   resolve does NOT arrive here: the browser fails it before it leaves the
 *   machine and the page sees a NetworkError, which shows up under `pageerror`.
 *   This listener covers connection refusals and TLS failures on a host that did
 *   resolve.
 * - responses with status >= 400 — the call reached the server and was refused.
 *
 * @param {{ maxEntries?: number, maxText?: number }} [limits] - bounds baked into the source.
 * @returns {string} the module source written to the engine checkout.
 */
export function consolePluginSource({ maxEntries, maxText } = {}) {
  return `${GENERATED_CONSOLE_MARKER}

/**
 * Captures console errors, uncaught exceptions and failed requests per tab.
 *
 * A ring buffer per tab, bounded in both length and text size: a page in a
 * render loop can produce thousands of errors a second, and an unbounded buffer
 * in the engine process is a memory leak in a long-lived server.
 *
 * @param {object} app - Express app.
 * @param {object} ctx - Shared plugin context.
 */
export function register(app, ctx) {
  const MAX_ENTRIES = ${Number(maxEntries) || 200}
  const MAX_TEXT = ${Number(maxText) || 2000}
  const MAX_PER_SOURCE = { error: 60, warning: 25, pageerror: 40, requestfailed: 60, http: 60 }

  // The tab id a page carries before the engine has assigned one. Entries
  // captured that early are re-keyed when \`tab:created\` arrives.
  const PENDING_TAB = '__pending__'

  // userId -> tabId -> { entries, counts, startedAt, url, pages? }
  const bySession = new Map()
  const seq = { n: 0 }

  const session = (userId) => {
    let s = bySession.get(userId)
    if (!s) { s = new Map(); bySession.set(userId, s) }
    return s
  }

  const trim = (text) => {
    const value = typeof text === 'string' ? text : String(text ?? '')
    return value.length > MAX_TEXT ? value.slice(0, MAX_TEXT) + '…[truncated]' : value
  }

  const record = (userId, tabId, kind, data) => {
    const tabs = session(userId)
    let tab = tabs.get(tabId)
    if (!tab) { tab = { entries: [], counts: {}, startedAt: Date.now(), url: '', pages: new Set() }; tabs.set(tabId, tab) }

    // A run-on error loop must not evict the first exception that explains it.
    const cap = MAX_PER_SOURCE[kind] ?? 20
    if ((tab.counts[kind] ?? 0) >= cap) return
    tab.counts[kind] = (tab.counts[kind] ?? 0) + 1

    tab.entries.push({ seq: ++seq.n, kind, at: Date.now(), ...data })
    if (tab.entries.length > MAX_ENTRIES) tab.entries.splice(0, tab.entries.length - MAX_ENTRIES)
  }

  // Render an argument the way a developer would read it at the console.
  // Playwright hands over a JSHandle, whose own toString is "JSHandle@object";
  // the preview is what actually carries the value, so prefer it.
  const render = (arg) => {
    try {
      if (arg === null) return 'null'
      if (arg === undefined) return 'undefined'
      if (typeof arg === 'string') return arg
      if (typeof arg === 'object') {
        if (arg instanceof Error) return arg.stack || (arg.name + ': ' + arg.message)
        try {
          if (typeof arg.preview === 'function') {
            const preview = arg.preview()
            if (preview && preview.previewProperties) {
              return '{' + preview.previewProperties
                .map((p) => p.name + ': ' + p.value)
                .join(', ') + '}'
            }
          }
        } catch { /* fall through to JSON */ }
        try { return JSON.stringify(arg) } catch { return String(arg) }
      }
      return String(arg)
    } catch { return '[unserializable]' }
  }

  // A listener is attached from THREE places, because each covers a gap the others
  // leave:
  //
  //   session:created  — the context exists but no page does yet, so
  //     \`context.on('page')\` is the only way to reach a page BEFORE its first
  //     navigation, which is when a page's own initialiser runs.
  //   tab:created      — covers a page the engine created some other way.
  //   tab:navigated    — everything after the first load.
  //
  // The first is the one that matters. \`tab:created\` fires at server.js:3043,
  // AFTER the initial \`goto\` resolved, so a listener attached only there misses
  // every error a page raises while loading — which is exactly what a broken
  // page reports. Measured, not assumed: with only \`tab:created\` wired, a page
  // that called \`console.error\` on load produced an empty report.
  const seen = new WeakSet()

  const attach = (userId, tabId, page) => {
    if (!page || typeof page.on !== 'function') return
    if (seen.has(page)) return
    seen.add(page)
    // Create the bucket up front so the page can be claimed by it, which is what
    // lets a later \`tab:created\` re-key these entries onto the tab id the engine
    // assigns.
    const tabs = session(userId)
    let bucket = tabs.get(tabId)
    if (!bucket) { bucket = { entries: [], counts: {}, startedAt: Date.now(), url: '', pages: new Set() }; tabs.set(tabId, bucket) }
    bucket.pages.add(page)

    page.on('console', (msg) => {
      let type = 'log'
      try { type = msg.type() } catch { return }
      if (type !== 'error' && type !== 'warning') return
      let text = ''
      try { text = msg.text() } catch { return }
      if (!text) {
        try { text = msg.args().map(render).join(' ') } catch { text = '' }
      }
      if (!text) return
      let location = null
      try {
        const loc = msg.location()
        if (loc && (loc.url || loc.lineNumber)) {
          location = { url: loc.url, line: loc.lineNumber, column: loc.columnNumber }
        }
      } catch { location = null }
      record(userId, tabId, type, { text: trim(text), location })
    })

    page.on('pageerror', (err) => {
      let text = ''
      try { text = (err && (err.stack || err.message)) || String(err) } catch { text = String(err) }
      record(userId, tabId, 'pageerror', { text: trim(text) })
    })

    page.on('requestfailed', (request) => {
      let failure = ''
      try { failure = request.failure() ? (request.failure().errorText || 'request failed') : 'request failed' } catch { failure = 'request failed' }
      let url = ''
      try { url = request.url() } catch { url = '' }
      let method = ''
      try { method = request.method() } catch { method = '' }
      // A resource the page cancelled itself is noise, not a failure.
      if (/ERR_ABORTED|NS_BINDING_ABORTED/i.test(failure)) return
      let type = ''
      try { type = request.resourceType() } catch { type = '' }
      record(userId, tabId, 'requestfailed', {
        text: trim(failure), url: trim(url), method, resourceType: type,
      })
    })

    page.on('response', (response) => {
      let status = 0
      try { status = response.status() } catch { return }
      if (status < 400) return
      let url = ''
      try { url = response.url() } catch { url = '' }
      let method = ''
      try { method = response.request().method() } catch { method = '' }
      record(userId, tabId, 'http', { status, text: trim('HTTP ' + status), url: trim(url), method })
    })

    page.on('framenavigated', (frame) => {
      let isMain = true
      try { isMain = frame === page.mainFrame() } catch { isMain = false }
      if (!isMain) return
      const tabs = session(userId)
      const tab = tabs.get(tabId)
      if (tab) { try { tab.url = frame.url() } catch { /* url unavailable */ } }
    })
  }

  // Every page this context will ever make is announced here first, before the
  // engine navigates it. A tab id is not known this early, so entries land under
  // a placeholder and the real tab claims them on \`tab:created\`.
  ctx.events.on('session:created', ({ userId, context }) => {
    if (!userId || !context || typeof context.on !== 'function') return
    try {
      context.on('page', (page) => {
        // The tab id is unknown here, so this is a per-session bucket; the
        // \`tab:created\` handler re-keys it once the engine assigns one.
        attach(String(userId), PENDING_TAB, page)
      })
    } catch { /* a context without page events simply gets no early capture */ }
  })

  ctx.events.on('tab:created', ({ userId, tabId, page }) => {
    if (!userId || !tabId) return
    const key = String(userId)
    const realTab = String(tabId)
    // Re-key anything the context hook captured for this page under the tab id
    // the engine has just assigned, so a caller filtering by tabId sees it.
    const pending = session(key).get(PENDING_TAB)
    if (pending && pending.pages && pending.pages.has(page)) {
      session(key).delete(PENDING_TAB)
      session(key).set(realTab, { entries: pending.entries, counts: pending.counts, startedAt: pending.startedAt, url: pending.url, pages: pending.pages })
    }
    attach(key, realTab, page)
  })

  ctx.events.on('tab:navigated', ({ userId, tabId, url }) => {
    if (!userId || !tabId) return
    const tab = session(String(userId)).get(String(tabId))
    if (tab && typeof url === 'string') tab.url = url
  })

  // A closed tab must not keep its entries alive; the page is gone by then.
  ctx.events.on('tab:destroyed', ({ userId, tabId }) => {
    if (!userId || !tabId) return
    const tabs = bySession.get(String(userId))
    if (tabs) tabs.delete(String(tabId))
  })

  ctx.events.on('session:destroyed', ({ userId }) => {
    if (userId) bySession.delete(String(userId))
  })

  app.get('/dsh-console/:userId', ctx.auth(), (req, res) => {
    const userId = req.params.userId
    const tabs = bySession.get(userId)
    if (!tabs) { res.json({ userId, tabs: [], total: 0, counts: {} }); return }

    const minSeverity = String(req.query.minSeverity || 'warning')
    const order = { error: 0, pageerror: 0, http: 1, requestfailed: 2, warning: 3 }
    const floor = order[minSeverity] ?? 0

    const out = []
    const counts = {}
    for (const [tabId, tab] of tabs) {
      const entries = tab.entries.filter((e) => (order[e.kind] ?? 9) <= floor)
      for (const entry of entries) counts[entry.kind] = (counts[entry.kind] ?? 0) + 1
      if (entries.length > 0) {
        out.push({ tabId, url: tab.url, startedAt: tab.startedAt, counts: tab.counts, entries })
      }
    }
    res.json({ userId, tabs: out, total: out.reduce((n, t) => n + t.entries.length, 0), counts, maxEntries: MAX_ENTRIES })
  })

  ctx.log('info', 'dsh-console: capturing console errors, uncaught exceptions and failed requests')
}
`
}